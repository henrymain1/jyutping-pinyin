"""Build extension/data/colloquial-keep.txt: words the extension must not split into parts.

Usage:
    python tools/build_colloquial_keep.py <dir>

<dir> holds the files from tools/fetch_colloquial_sources.py (only cedict.txt.gz is read).

When a word or phrase on a page isn't in colloquial.tsv, the extension tags the parts it
can find: rows of two or more characters, and single characters marked "part" (不想 →
"不 → 唔"). That's wrong for words Cantonese says the same way, so these are kept whole:
  - words reviewed and left out in tools/colloquial_skip.tsv (不過, 不斷);
  - four-character idioms in CC-CEDICT with a part character in them (愛不釋手);
  - CC-CEDICT words that contain a listed word without being one (下午茶, 不要臉).
Only words that would otherwise get a tag are written. Rerun after editing colloquial.tsv
or the skip list.
"""

import gzip
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "extension" / "data"
SKIP = ROOT / "tools" / "colloquial_skip.tsv"
OUT = DATA / "colloquial-keep.txt"


def rows(path):
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            yield line.split("\t")


def main(folder):
    sys.stdout.reconfigure(encoding="utf-8")
    listed, parts = set(), set()
    for cells in rows(DATA / "colloquial.tsv"):
        forms = cells[0].split(",")
        listed.update(forms)
        if len(cells) > 3 and cells[3] == "part":
            parts.update(forms)
    words = {form for form in listed if len(form) > 1}

    def contains_word(text):
        """Whether a listed word of two or more characters is inside text, shorter than it."""
        n = len(text)
        return any(text[i:j] in words for i in range(n) for j in range(i + 2, n + 1) if j - i < n)

    def would_split(text):
        return any(ch in parts for ch in text) or contains_word(text)

    keep = {form for cells in rows(SKIP) for form in cells[0].split(",")}
    idioms = compounds = 0
    for line in gzip.open(Path(folder) / "cedict.txt.gz", "rt", encoding="utf-8"):
        m = re.match(r"(\S+) (\S+) \[[^\]]*\] /(.*)/", line)
        if not m or line.startswith("#"):
            continue
        trad, simp, defs = m.groups()
        for form in {trad, simp}:
            if form in listed or len(form) < 3:
                continue
            if len(form) == 4 and "(idiom)" in defs and any(ch in parts for ch in form):
                keep.add(form)
                idioms += 1
            elif contains_word(form):
                keep.add(form)
                compounds += 1

    keep = sorted(form for form in keep - listed if len(form) > 1 and would_split(form))
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Generated by tools/build_colloquial_keep.py: words Cantonese says the same way,\n")
        f.write("# which the extension leaves whole instead of tagging their parts. One per line.\n")
        f.write("# From tools/colloquial_skip.tsv and CC-CEDICT (CC BY-SA 4.0).\n")
        f.write("\n".join(keep) + "\n")
    print(f"{len(keep)} words in {OUT.relative_to(ROOT)} ({OUT.stat().st_size / 1e3:.0f} KB); "
          f"from CC-CEDICT: {idioms} idiom forms, {compounds} compound forms")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
